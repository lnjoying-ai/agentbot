const state = reactive({
    locale: resolveLocale()
});
function resolveLocale() {
    if (typeof window === "undefined")
        return "zh-CN";
    const saved = normalizeLocale(window.localStorage.getItem(STORAGE_KEY));
    if (saved)
        return saved;
    const preferred = normalizeLocale(window.navigator.language) || normalizeLocale(window.navigator.languages?.[0]);
    return preferred || "zh-CN";
}
function normalizeLocale(value) {
    if (!value)
        return null;
    const normalized = value.replace("_", "-");
    if (normalized in messages)
        return normalized;
    if (normalized.toLowerCase().startsWith("zh"))
        return "zh-CN";
    if (normalized.toLowerCase().startsWith("en"))
        return "en-US";
    return null;
}
function setLocale(locale) {
    if (!messages[locale])
        return;
    state.locale = locale;
    if (typeof window !== "undefined") {
        window.localStorage.setItem(STORAGE_KEY, locale);
    }
}
function t(key, params) {
    const dict = messages[state.locale];
    const fallback = messages["zh-CN"];
    let text = dict[key] ?? fallback[key] ?? key;
    if (params) {
        Object.entries(params).forEach(([paramKey, paramValue]) => {
            text = text.replace(new RegExp(`\\{${paramKey}\\}`, "g"), String(paramValue));
        });
    }
    return text;
}
export function useI18n() {
    return {
        t,
        locale: computed(() => state.locale),
        setLocale,
        supportedLocales: Object.keys(messages)
    };
}
